# 클라이언트가 보낸 식별자를 저장 형식으로 맞추는 공용 변환. (Issue #116)
#
#   - incident_id는 서버가 발급하는 불투명 식별자다. 공개 계약은 문자열로 받고
#     UUID 형식을 요구하지 않는다 — 형식이 어긋난 값은 계약 위반이 아니라
#     "그런 인시던트가 없는 것"이므로 조회부가 404로 답한다 (PR #119 리뷰).
#   - 저장 컬럼이 PG uuid라 형식이 어긋난 값을 그대로 조회하면 캐스트 오류로
#     500이 된다. 조회 전에 반드시 이 변환을 거친다.
# ==============================================================================

from __future__ import annotations

import uuid
from typing import Optional


def canonical_id(value: str) -> Optional[str]:
    """저장 값과 같은 정규형(소문자·하이픈)으로 맞춘다. 형식이 어긋나면 None.

    대문자·하이픈 없는 표기도 같은 식별자로 받아들이므로, 표기 차이로 조회나
    재요청 비교가 흔들리지 않는다.
    """
    try:
        return str(uuid.UUID(value))
    except ValueError:
        return None
