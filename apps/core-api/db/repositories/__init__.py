#   - Repository는 commit하지 않는다. 트랜잭션 경계는 호출부(Workflow)가 소유한다.
#   - 상태 갱신은 조건부 UPDATE(expected → next)로만 하고 성공 여부(bool)를 돌려준다
#     — 동시 요청이 서로의 전이를 덮어쓰지 못하게 하는 두 번째 층이다.
#   - 생성 메서드는 flush까지 수행해 제약 위반을 호출 지점에서 드러낸다.
